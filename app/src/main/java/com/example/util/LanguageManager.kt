object LanguageManager {

    private const val PREFS_NAME = "baytulilm_app_settings_prefs"
    private const val KEY_SELECTED_LANG = "selected_language_code"
    private const val KEY_FIRST_LAUNCH = "is_first_launch_done"
    private const val KEY_SELECTED_THEME = "selected_theme_mode" // "System", "Light", "Dark"

    val supportedLanguages = listOf(
        AppLanguage("ur", "Urdu", "اردو", "🇵🇰", isRtl = true),
        AppLanguage("en", "English", "English", "🇺🇸", isRtl = false),
