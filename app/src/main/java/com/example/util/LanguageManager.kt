        AppLanguage("tr", "Turkish", "Türkçe", "🇹🇷", isRtl = false),
        AppLanguage("id", "Indonesian", "Bahasa Indonesia", "🇮🇩", isRtl = false),
        AppLanguage("hi", "Hindi", "हिन्दी", "🇮🇳", isRtl = false),
        AppLanguage("bn", "Bengali", "বাংলা", "🇧🇩", isRtl = false),
        AppLanguage("fr", "French", "Français", "🇫🇷", isRtl = false),
        AppLanguage("de", "German", "Deutsch", "🇩🇪", isRtl = false),
        AppLanguage("es", "Spanish", "Español", "🇪🇸", isRtl = false),
        AppLanguage("ru", "Russian", "Русский", "🇷🇺", isRtl = false),
        AppLanguage("zh", "Chinese", "中文", "🇨🇳", isRtl = false),
        AppLanguage("fa", "Persian", "فارسی", "🇮🇷", isRtl = true),
        AppLanguage("ps", "Pashto", "پښتو", "🇦🇫", isRtl = true),
        AppLanguage("ckb", "Kurdish", "کوردی", "🇮🇶", isRtl = true),
        AppLanguage("sw", "Swahili", "Kiswahili", "🇹🇿", isRtl = false),
        AppLanguage("ms", "Malay", "Bahasa Melayu", "🇲🇾", isRtl = false)
    )

    private val _currentLanguage = MutableStateFlow(supportedLanguages.first())
    val currentLanguage: StateFlow<AppLanguage> = _currentLanguage.asStateFlow()

    private val _currentTheme = MutableStateFlow("System") // "System", "Light", "Dark"
    val currentTheme: StateFlow<String> = _currentTheme.asStateFlow()

    private val _isFirstLaunch = MutableStateFlow(true)
    val isFirstLaunch: StateFlow<Boolean> = _isFirstLaunch.asStateFlow()

    fun init(context: Context) {
        val prefs = getPrefs(context)
        val savedCode = prefs.getString(KEY_SELECTED_LANG, "ur") ?: "ur"
        val savedTheme = prefs.getString(KEY_SELECTED_THEME, "System") ?: "System"
        val firstLaunchDone = prefs.getBoolean(KEY_FIRST_LAUNCH, false)

        val foundLang = supportedLanguages.find { it.code == savedCode || it.englishName.equals(savedCode, ignoreCase = true) }
            ?: supportedLanguages.first()

        _currentLanguage.value = foundLang
        _currentTheme.value = savedTheme
        _isFirstLaunch.value = !firstLaunchDone

        applyLocale(context, foundLang.code)
    }

    private fun getPrefs(context: Context): SharedPreferences {
        return context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
    }

    fun setLanguage(context: Context, language: AppLanguage) {
        _currentLanguage.value = language
        val prefs = getPrefs(context)
        prefs.edit().putString(KEY_SELECTED_LANG, language.code).apply()
        applyLocale(context, language.code)
    }

    fun setLanguageByCodeOrName(context: Context, lang: String) {
        val found = supportedLanguages.find {
            it.code.equals(lang, ignoreCase = true) || it.englishName.equals(lang, ignoreCase = true)
        } ?: supportedLanguages.first()
        setLanguage(context, found)
    }

    fun markFirstLaunchCompleted(context: Context) {
        _isFirstLaunch.value = false
        getPrefs(context).edit().putBoolean(KEY_FIRST_LAUNCH, true).apply()
    }

    fun setTheme(context: Context, themeMode: String) {
        _currentTheme.value = themeMode
        getPrefs(context).edit().putString(KEY_SELECTED_THEME, themeMode).apply()
    }

    private fun applyLocale(context: Context, langCode: String) {
        try {
            val locale = Locale(langCode)
            Locale.setDefault(locale)
            val resources = context.resources
            val config = Configuration(resources.configuration)
            config.setLocale(locale)
            resources.updateConfiguration(config, resources.displayMetrics)
        } catch (e: Exception) {
            e.printStackTrace()
        }
    }

    fun getString(key: String, langCode: String = _currentLanguage.value.code): String {
        val dict = translations[langCode] ?: translations["ur"] ?: translations["en"] ?: emptyMap()
        return dict[key] ?: translations["ur"]?.get(key) ?: translations["en"]?.get(key) ?: key
    }
}

// Global Compose Provider for localized strings
val LocalAppLanguage = staticCompositionLocalOf { LanguageManager.supportedLanguages.first() }

@Composable
fun lStr(key: String): String {
    val currentLang = LocalAppLanguage.current
    return LanguageManager.getString(key, currentLang.code)
}

@Composable
fun LocalizedApp(
    context: Context,
    content: @Composable () -> Unit
) {
    val lang by LanguageManager.currentLanguage.collectAsState()
    val layoutDirection = if (lang.isRtl) LayoutDirection.Rtl else LayoutDirection.Ltr

    CompositionLocalProvider(
        LocalAppLanguage provides lang,
        LocalLayoutDirection provides layoutDirection
    ) {
        content()
    }
}

